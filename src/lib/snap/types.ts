import type { Msg, Text } from "@/lib/i18n/types";
import type { VisionPayload } from "./vision";
import type { ReceiptItem } from "@/lib/finance/types";

export type DocKind = "listing" | "receipt" | "bill" | "payslip" | "note" | "other";
export const DOC_KINDS: readonly DocKind[] = ["listing", "receipt", "bill", "payslip", "note", "other"];
export const MAX_AMOUNT = 50_000_000;

/** Structured result of any tier. Small on purpose: this is all the twin needs. */
export interface Extraction {
  kind: DocKind;
  /** Listing: price. Receipt/bill: printed total. Payslip: net pay. Note: target amount. */
  amount?: number;
  merchant?: string;
  date?: string;
  location?: string;
  rooms?: number;
  /** Listing / floor plan: verified net living area in m². */
  areaM2?: number;
  category?: string;
  currency?: string;
  items?: ReceiptItem[];
  label?: string;
  /** Display descriptor for a label generated by a local extractor. */
  labelMsg?: Msg;
  year?: number;
  iban?: string;
  message?: string;
  /** Structured vision analysis and deterministic verification for floor plans and charts. */
  vision?: VisionPayload;
}

export type Tier = 0 | 1 | 2;

export interface PipelineStep {
  name: Text;
  ms: number;
  detail?: Text;
  bytes?: number;
}

export interface Usage {
  promptTokens: number;
  completionTokens: number;
  costUsd: number;
  model: string;
  /** "llm" = real model call; "local" = no LLM; "offline" = no model endpoint configured, local heuristics used. */
  mode: "llm" | "local" | "offline";
  /**
   * Where the token counts come from. "estimated": the provider reported none, so they are ~4 characters per token.
   * Estimated entries never count as measured (`usageKnown` is false for them). Absent = reported or local.
   */
  tokenBasis?: "reported" | "estimated";
  /**
   * Where `costUsd` comes from. "estimated": tokens × list price. "unknown": no price for this model, `costUsd` is 0
   * and the entry is left out of every cost total. Absent = reported or local.
   */
  costBasis?: "reported" | "estimated" | "unknown";
}

export interface SnapResult {
  tier: Tier;
  extraction: Extraction;
  outcome: "ok" | "partial" | "failed";
  route: "qr" | "cache" | "local-regex" | "text-llm" | "vision-llm" | "vision-plan" | "vision-chart" | "offline-heuristic";
  steps: PipelineStep[];
  usage: Usage;
  usageKnown: boolean;
  /** What actually left the browser (image data truncated for display). */
  payload: unknown;
  ocrConfidence?: number;
  imageSize: { width: number; height: number };
  preview?: string;
  naiveImage?: string;
  fieldsMissing?: string[];
  /** Why vision was needed for this document (shown in Review and Inspector). */
  visionReason?: Text;
  /** Pixel dimensions of the cropped image that left the device on a vision route. */
  cropSize?: { width: number; height: number };
}

export function isAmount(value: unknown): value is number {
  return typeof value === "number" && Number.isFinite(value) && value >= 0 && value <= MAX_AMOUNT;
}

export function extractionStatus(extraction: Extraction): Pick<SnapResult, "outcome" | "fieldsMissing"> {
  if (extraction.vision?.kind === "chart") {
    const c = extraction.vision.chart;
    return c.allocation || (c.latestValueChf !== undefined && c.latestValueChf > 0)
      ? { outcome: "ok" }
      : { outcome: "partial", fieldsMissing: ["amount"] };
  }
  if (extraction.kind === "other") return { outcome: "failed", fieldsMissing: ["kind", "amount"] };
  if (!isAmount(extraction.amount)) return { outcome: "partial", fieldsMissing: ["amount"] };
  return { outcome: "ok" };
}
